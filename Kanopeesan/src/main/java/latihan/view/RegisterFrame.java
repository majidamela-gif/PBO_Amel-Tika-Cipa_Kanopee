    private void DaftarRegistButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DaftarRegistButtonActionPerformed
        // TODO add your handling code here:
        String email = EmailRegistField.getText().trim();
        String username = UsernameRegistField.getText().trim();
        String password = new String(PasswordRegistField.getPassword());

        // Validasi kosong
        if (
                email.isEmpty()
                || username.isEmpty()
                || password.isEmpty()
        ) {
            JOptionPane.showMessageDialog(
                    this,
                    "Semua field wajib diisi.",
                    "Registrasi",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        // Validasi email sederhana
        if (!email.matches(
                "^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$"
        )) {
            JOptionPane.showMessageDialog(
                    this,
                    "Format email tidak valid.",
                    "Registrasi",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        // Validasi username
        if (username.length() < 3) {
            JOptionPane.showMessageDialog(
                    this,
                    "Username minimal 3 karakter.",
                    "Registrasi",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        // Validasi password
        if (password.length() < 8) {
            JOptionPane.showMessageDialog(
                    this,
                    "Password minimal 8 karakter.",
                    "Registrasi",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

                try {
            // Cek username/email
            if (userRepository.existsByUsernameOrEmail(username, email)) {
                JOptionPane.showMessageDialog(
                        this,
                        "Username atau email sudah digunakan.",
                        "Registrasi Gagal",
                        JOptionPane.ERROR_MESSAGE
                );
                return;
            }

            // Hash password lalu simpan user baru
            User user = new User();
            user.setEmail(email);
            user.setUsername(username);
            user.setPassword(PasswordUtil.hashPassword(password));
            userRepository.insert(user);

            JOptionPane.showMessageDialog(
                    this,
                    "Registrasi berhasil!\n"
                    + "Silakan login menggunakan akun kamu.",
                    "Registrasi Berhasil",
                    JOptionPane.INFORMATION_MESSAGE
            );

            LoginFrame loginFrame = new LoginFrame();
            loginFrame.setLocationRelativeTo(null);
            loginFrame.setVisible(true);
            dispose();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Registrasi gagal.\n"
                    + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_DaftarRegistButtonActionPerformed

