    private void LoginButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_LoginButtonActionPerformed
        // TODO add your handling code here:
        String username = UsernameLoginField.getText().trim();
        String password = new String(PasswordLoginField.getPassword());

        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Username dan password wajib diisi.",
                    "Login",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        String sql = """
                SELECT id, username, email, password, role
                FROM users
                WHERE username = ?
                """;

        try (
                Connection conn = DBConnection.getConnection();
                PreparedStatement stmt = conn.prepareStatement(sql)
        ) {
            stmt.setString(1, username);
            try (ResultSet rs = stmt.executeQuery()) {
                if (!rs.next()) {
                    JOptionPane.showMessageDialog(
                            this,
                            "Username atau password salah.",
                            "Login Gagal",
                            JOptionPane.ERROR_MESSAGE
                    );
                    return;
                }

                String storedPassword = rs.getString("password");
                boolean passwordValid =
                        PasswordUtil.verifyPassword(
                                password,
                                storedPassword
                        );

                if (!passwordValid) {
                    JOptionPane.showMessageDialog(
                            this,
                            "Username atau password salah.",
                            "Login Gagal",
                            JOptionPane.ERROR_MESSAGE
                    );
                    return;
                }

                String role = rs.getString("role");

                // Tombol login biasa hanya untuk USER
                if (!"USER".equalsIgnoreCase(role)) {
                    JOptionPane.showMessageDialog(
                            this,
                            "Akun admin harus login melalui tombol Login sebagai Admin.",
                            "Login",
                            JOptionPane.WARNING_MESSAGE
                    );
                    return;
                }

                Session.login(
                        rs.getInt("id"),
                        rs.getString("username"),
                        rs.getString("email"),
                        role
                );

                JOptionPane.showMessageDialog(
                        this,
                        "Login berhasil. Selamat datang, "
                        + rs.getString("username") + "!",
                        "Login Berhasil",
                        JOptionPane.INFORMATION_MESSAGE
                );

                UserFrame userFrame = new UserFrame();
                userFrame.setLocationRelativeTo(null);
                userFrame.setVisible(true);
                dispose();
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Tidak dapat terhubung ke database.\n"
                    + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_LoginButtonActionPerformed

